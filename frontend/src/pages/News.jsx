const categories = [
  { id: 'all', label: 'Все новости' },
  { id: 'control', label: 'Контроль и проверки' },
  { id: 'services', label: 'Сервисы и цифровизация' },
  { id: 'misc', label: 'Прочее' },
];

const importanceConfig = {
  high:   { label: 'Важно',     className: 'badge-high' },
  medium: { label: 'Актуально', className: 'badge-medium' },
  low:    { label: 'Интересно', className: 'badge-low' },
};

export default function News() {
  const [selectedCategory, setSelectedCategory] = useState('all');
  const [openArticle, setOpenArticle] = useState(null);

  const filtered = selectedCategory === 'all'
    ? newsItems
    : newsItems.filter(n => n.category === selectedCategory);

  const sorted = [...filtered].sort((a, b) => {
    const p = { high: 0, medium: 1, low: 2 };
    return p[a.importance] - p[b.importance];
  });

  const categoryCounts = Object.fromEntries(
    categories.map(c => [c.id, c.id === 'all' ? newsItems.length : newsItems.filter(n => n.category === c.id).length])
  );

  return (
    <section className="page-section">
      <div className="section-inner">

        <div className="page-header">
          <h1>Новости ЖКХ</h1>
          <p className="page-subtitle">
            Официальные новости Государственной жилищной инспекции Республики Дагестан
          </p>
        </div>

        {/* Фильтры */}
        <div className="news-filters">
          {categories.map(cat => (
            <button
              key={cat.id}
              className={`news-filter-btn ${selectedCategory === cat.id ? 'active' : ''}`}
              onClick={() => setSelectedCategory(cat.id)}
            >
              {cat.label}
              <span className="filter-count">{categoryCounts[cat.id]}</span>
            </button>
          ))}
        </div>

        {/* Список новостей */}
        <div className="news-list">
          {sorted.map(news => {
            const imp = importanceConfig[news.importance];
            return (
              <article key={news.id} className={`news-card news-importance-${news.importance}`}>
                <div className="news-icon">{news.icon}</div>
                <div className="news-content">
                  <div className="news-meta">
                    <span className="news-date">📅 {news.date}</span>
                    <span className={`news-badge ${imp.className}`}>{imp.label}</span>
                    <span className="news-views">👁 {news.views}</span>
                  </div>
                  <h3 className="news-title">{news.title}</h3>
                  <p className="news-excerpt">{news.excerpt}</p>
                  <div className="news-actions">
                    <button className="link-btn" onClick={() => setOpenArticle(news)}>
                      Читать полностью →
                    </button>
                  </div>
                </div>
              </article>
            );
          })}
        </div>

        {sorted.length === 0 && (
          <div className="empty-state">
            <p>Новостей в этой категории пока нет</p>
          </div>
        )}

        {/* Ссылка на оригинальный сайт */}
        <div className="news-source-link">
          <p>
            Все новости ГЖИ Республики Дагестан —{' '}
            <a href="https://daggji.e-dag.ru/news" target="_blank" rel="noreferrer">
              gzhi.e-dag.ru
            </a>
          </p>
        </div>
      </div>

      {/* Модальное окно статьи */}
      {openArticle && (
        <div className="news-modal-overlay" onClick={() => setOpenArticle(null)}>
          <div className="news-modal" onClick={e => e.stopPropagation()}>
            <button className="news-modal-close" onClick={() => setOpenArticle(null)}>✕</button>

            <div className="news-modal-meta">
              <span className="news-date">📅 {openArticle.date}</span>
              <span className={`news-badge ${importanceConfig[openArticle.importance].className}`}>
                {importanceConfig[openArticle.importance].label}
              </span>
            </div>

            <div className="news-modal-icon">{openArticle.icon}</div>
            <h2 className="news-modal-title">{openArticle.title}</h2>

            <div className="news-modal-body">
              {openArticle.fullText.split('\n').map((line, i) =>
                line.trim() === ''
                  ? <br key={i} />
                  : <p key={i}>{line}</p>
              )}
            </div>

            <div className="news-modal-footer">
              <a
                href={openArticle.source}
                target="_blank"
                rel="noreferrer"
                className="news-source-btn"
              >
                Источник: daggji.e-dag.ru ↗
              </a>
            </div>
          </div>
        </div>
      )}
    </section>
  );
}
